type NeetSubject = 'Physics' | 'Chemistry' | 'Botany' | 'Zoology';
type NeetCompactTuple = [number, NeetSubject, string, number, 0 | 1 | 2 | 3];

const OPTION_LETTERS = ['A', 'B', 'C', 'D'] as const;

function buildNeetQuestions(params: {
  testId: string;
  prefix: string;
  assetFolder: string;
  testLabel: string;
  specs: NeetCompactTuple[];
}): TestQuestionRecord[] {
  const { testId, prefix, assetFolder, testLabel, specs } = params;
  return specs.map(([q, subject, chapter, page, ans]) => {
    const num = String(q).padStart(3, '0');
    return {
      id: `q-${prefix}-${num}`,
      testId,
      questionNumber: q,
      subjectName: subject,
      chapterName: chapter,
      questionType: 'single-mcq',
      questionText: `${testLabel} · Q${q} (${subject} — ${chapter}). Refer to the cropped question image.`,
      questionImageUrl: `/assets/mocks/${assetFolder}/q${num}.png`,
      optionTexts: ['Option A', 'Option B', 'Option C', 'Option D'],
      correctOptionIndices: [ans],
      solutionText: `Correct Option: (${OPTION_LETTERS[ans]}). Refer to the cropped NCERT solution for ${subject} — ${chapter}.`,
      solutionImageUrl: `/assets/mocks/${assetFolder}/s${num}.png`,
      sourcePageNumber: page,
      positiveMarks: 4,
      negativeMarks: 1,
      testStatus: 'published',
    };
  });
}

