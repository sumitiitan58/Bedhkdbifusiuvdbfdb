/**
 * Map of existing chapterId -> required additional cohorts so shared Physics & Chemistry
 * chapters (originally JEE-only in JEE_CONCISE_CHAPTERS) also surface cleanly for NEET
 * students browsing their Formula Sheets (while keeping JEE Concise Notes strictly JEE-only).
 */
export const PCMB_FORMULA_CHAPTER_COHORT_EXPANSIONS: Record<string, string[]> = (() => {
  const map: Record<string, Set<string>> = {};
  for (const spec of FORMULA_SPECS) {
    if (spec.newChapter) continue;
    if (!map[spec.chapterId]) map[spec.chapterId] = new Set<string>();
    for (const c of spec.cohorts) map[spec.chapterId].add(c);
  }
  const result: Record<string, string[]> = {};
  for (const [chapId, set] of Object.entries(map)) {
    result[chapId] = Array.from(set);
  }
  return result;
})();

